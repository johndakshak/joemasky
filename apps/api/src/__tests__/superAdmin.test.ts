import { describe, it, expect, vi, beforeEach } from "vitest";
import request from "supertest";

// ── Module mocks — must be declared before any imports that trigger them ─────

// Mock cloudinary so the product controller's import-time env check does not throw.
vi.mock("../lib/cloudinary", () => ({
  cloudinary: {},
  upload: { single: () => (_req: unknown, _res: unknown, next: () => void) => next() },
  uploadImageBuffer: vi.fn(),
}));

// Mock Prisma so no real database connection is made.
vi.mock("../lib/prisma", () => ({
  prisma: {
    admin: {
      findUnique: vi.fn(),
      findMany: vi.fn(),
      create: vi.fn(),
      update: vi.fn(),
    },
    adminInvite: {
      create: vi.fn(),
      findUnique: vi.fn(),
      update: vi.fn(),
    },
  },
}));

import app from "../app";
import { prisma } from "../lib/prisma";
import jwt from "jsonwebtoken";

const SECRET = process.env.JWT_SECRET ?? "test-secret-for-unit-tests";
process.env.JWT_SECRET = SECRET;

function makeToken(id: number, role: "SUPER_ADMIN" | "ADMIN") {
  return jwt.sign({ id, role }, SECRET, { expiresIn: "15m" });
}

const superAdminToken = makeToken(1, "SUPER_ADMIN");
const regularAdminToken = makeToken(2, "ADMIN");

// ── Shared mock objects ──────────────────────────────────────────────────────

const activeSuperAdmin = {
  id: 1, name: "Super User", email: "super@joemasky.com",
  role: "SUPER_ADMIN", isActive: true, createdAt: new Date(),
};

const activeRegularAdmin = {
  id: 2, name: "Regular Admin", email: "admin@joemasky.com",
  role: "ADMIN", isActive: true, createdAt: new Date(),
};

const frozenAdmin = {
  id: 3, name: "Frozen Admin", email: "frozen@joemasky.com",
  role: "ADMIN", isActive: false, createdAt: new Date(),
};

// requireAdmin middleware calls prisma.admin.findUnique to check isActive.
// Configure the mock to return the right admin for each decoded token id.
function mockAdminLookup(id: number) {
  const map: Record<number, { isActive: boolean }> = {
    1: { isActive: true },   // super admin
    2: { isActive: true },   // regular admin
    3: { isActive: false },  // frozen admin
  };
  return map[id] ?? null;
}

beforeEach(() => {
  vi.clearAllMocks();
  // Default: requireAdmin middleware succeeds for valid tokens.
  (prisma.admin.findUnique as ReturnType<typeof vi.fn>).mockImplementation(
    ({ where }: { where: { id?: number; email?: string } }) => {
      if (where.id !== undefined) return Promise.resolve(mockAdminLookup(where.id));
      return Promise.resolve(null);
    }
  );
});

// ── 1. Super Admin can generate an invite ───────────────────────────────────

describe("POST /admin/invite", () => {
  it("1. Super Admin can generate an invite", async () => {
    const expiresAt = new Date(Date.now() + 86400_000);
    // The controller generates the raw token internally via crypto.randomBytes,
    // stores only the hash, and returns the raw token. Mock the DB create call.
    (prisma.adminInvite.create as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      id: 1,
      tokenHash: "sha256-hash-of-token",
      expiresAt,
      createdById: 1,
      usedById: null,
      usedAt: null,
      createdAt: new Date(),
    });

    const res = await request(app)
      .post("/admin/invite")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).toBe(201);
    expect(res.body.success).toBe(true);
    // The raw token is a 64-character hex string generated by crypto.randomBytes(32).
    expect(typeof res.body.data.token).toBe("string");
    expect(res.body.data.token).toHaveLength(64);
    expect(res.body.data.expiresAt).toBeDefined();

    // Expiry must be ~24 hours from now, not today.
    const issuedAt = Date.now();
    const expiresAtMs = new Date(res.body.data.expiresAt).getTime();
    const diffMs = expiresAtMs - issuedAt;
    // Allow ±5 s of clock drift in CI; the lifetime must be 24 h (86 400 000 ms).
    expect(diffMs).toBeGreaterThan(86_400_000 - 5_000);
    expect(diffMs).toBeLessThan(86_400_000 + 5_000);
  });

  // 2. Regular admin cannot generate an invite
  it("2. Regular admin cannot generate an invite (403)", async () => {
    const res = await request(app)
      .post("/admin/invite")
      .set("Authorization", `Bearer ${regularAdminToken}`);

    expect(res.status).toBe(403);
    expect(res.body.success).toBe(false);
  });

  // 3. Unauthenticated request is rejected
  it("3. Unauthenticated request is rejected (401)", async () => {
    const res = await request(app).post("/admin/invite");

    expect(res.status).toBe(401);
    expect(res.body.success).toBe(false);
  });
});

// ── 4 & 5. Invite expiration and reuse ──────────────────────────────────────

describe("POST /register/admin — invite validation", () => {
  const baseBody = {
    name: "New Admin",
    email: "new@joemasky.com",
    password: "Secure1@Password",
  };

  // 4. Expired invite is rejected
  it("4. Expired invite is rejected (400)", async () => {
    (prisma.adminInvite.findUnique as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      id: 2,
      tokenHash: "sha256-hash-of-expired-token",
      expiresAt: new Date(Date.now() - 1000), // already past
      usedAt: null,
      createdById: 1,
      usedById: null,
      createdAt: new Date(),
    });

    const res = await request(app)
      .post("/register/admin")
      .send({ ...baseBody, inviteToken: "expired-token" });

    expect(res.status).toBe(400);
    expect(res.body.message).toMatch(/expired/i);
  });

  // 5. Already-used invite cannot be accepted
  it("5. Already-used invite cannot be accepted (400)", async () => {
    (prisma.adminInvite.findUnique as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      id: 3,
      tokenHash: "sha256-hash-of-used-token",
      expiresAt: new Date(Date.now() + 86400_000),
      usedAt: new Date(), // already used
      createdById: 1,
      usedById: 10,
      createdAt: new Date(),
    });

    const res = await request(app)
      .post("/register/admin")
      .send({ ...baseBody, inviteToken: "used-token" });

    expect(res.status).toBe(400);
    expect(res.body.message).toMatch(/already been used/i);
  });

  // Invalid / non-existent token
  it("5b. Non-existent invite token is rejected (400)", async () => {
    (prisma.adminInvite.findUnique as ReturnType<typeof vi.fn>).mockResolvedValueOnce(null);

    const res = await request(app)
      .post("/register/admin")
      .send({ ...baseBody, inviteToken: "no-such-token" });

    expect(res.status).toBe(400);
    expect(res.body.message).toMatch(/invalid invite token/i);
  });
});

// ── 6 & 7. Freeze / unfreeze ─────────────────────────────────────────────────

describe("PATCH /freeze/:id and /unfreeze/:id", () => {
  // 6a. Super Admin can freeze an eligible admin
  it("6a. Super Admin can freeze an active admin", async () => {
    (prisma.admin.findUnique as ReturnType<typeof vi.fn>)
      // First call: requireAdmin checks the token holder (super admin, isActive: true)
      .mockResolvedValueOnce({ isActive: true })
      // Second call: findAdminById fetches the target
      .mockResolvedValueOnce(activeRegularAdmin);

    (prisma.admin.update as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      ...activeRegularAdmin, isActive: false,
    });

    const res = await request(app)
      .patch("/freeze/2")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).toBe(200);
    expect(res.body.data.isActive).toBe(false);
  });

  // 6b. Super Admin can unfreeze an admin
  it("6b. Super Admin can unfreeze a frozen admin", async () => {
    (prisma.admin.findUnique as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce({ isActive: true })   // requireAdmin: token holder
      .mockResolvedValueOnce(frozenAdmin);           // findAdminById: target

    (prisma.admin.update as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      ...frozenAdmin, isActive: true,
    });

    const res = await request(app)
      .patch("/unfreeze/3")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).toBe(200);
    expect(res.body.data.isActive).toBe(true);
  });

  // 7. Frozen admin cannot access protected routes
  it("7. Frozen admin is blocked by requireAdmin (401)", async () => {
    // Override the default mock so the frozen admin's isActive check returns false.
    (prisma.admin.findUnique as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      isActive: false,
    });

    const frozenToken = makeToken(3, "ADMIN");

    const res = await request(app)
      .get("/admin/admins")
      .set("Authorization", `Bearer ${frozenToken}`);

    expect(res.status).toBe(401);
  });

  // 8. Regular admin cannot freeze another admin
  it("8. Regular admin cannot freeze an admin (403)", async () => {
    const res = await request(app)
      .patch("/freeze/3")
      .set("Authorization", `Bearer ${regularAdminToken}`);

    expect(res.status).toBe(403);
  });

  // 8b. Regular admin cannot unfreeze
  it("8b. Regular admin cannot unfreeze an admin (403)", async () => {
    const res = await request(app)
      .patch("/unfreeze/3")
      .set("Authorization", `Bearer ${regularAdminToken}`);

    expect(res.status).toBe(403);
  });

  // 9. Super Admin cannot freeze their own account
  it("9. Super Admin cannot freeze their own account (400)", async () => {
    const res = await request(app)
      .patch("/freeze/1")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).toBe(400);
    expect(res.body.message).toMatch(/cannot freeze your own/i);
  });

  // Already-frozen admin re-freeze returns 409
  it("6c. Freezing an already-frozen admin returns 409", async () => {
    (prisma.admin.findUnique as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce({ isActive: true })
      .mockResolvedValueOnce(frozenAdmin);

    const res = await request(app)
      .patch("/freeze/3")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).toBe(409);
    expect(res.body.message).toMatch(/already frozen/i);
  });

  // Already-active admin re-unfreeze returns 409
  it("6d. Unfreezing an already-active admin returns 409", async () => {
    (prisma.admin.findUnique as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce({ isActive: true })
      .mockResolvedValueOnce(activeRegularAdmin);

    const res = await request(app)
      .patch("/unfreeze/2")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).toBe(409);
    expect(res.body.message).toMatch(/already active/i);
  });
});

// ── GET /admin/admins — route registration and authorization ─────────────────

describe("GET /admin/admins", () => {
  it("A. Super Admin retrieves admin list (200 + correct shape)", async () => {
    (prisma.admin.findMany as ReturnType<typeof vi.fn>).mockResolvedValueOnce([
      activeSuperAdmin,
      activeRegularAdmin,
    ]);

    const res = await request(app)
      .get("/admin/admins")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).toBe(200);
    expect(res.body.success).toBe(true);
    // data must be an array
    expect(Array.isArray(res.body.data)).toBe(true);
    expect(res.body.data).toHaveLength(2);

    // Each record must include the fields the frontend AdminRecord interface requires.
    const [first] = res.body.data;
    expect(first).toHaveProperty("id");
    expect(first).toHaveProperty("name");
    expect(first).toHaveProperty("email");
    expect(first).toHaveProperty("role");
    expect(first).toHaveProperty("isActive");
    expect(first).toHaveProperty("createdAt");
    // Password must never be included.
    expect(first).not.toHaveProperty("password");
  });

  it("B. Route is registered — does not return 404", async () => {
    // Even without mocking findMany (will 500), the route must NOT 404.
    const res = await request(app)
      .get("/admin/admins")
      .set("Authorization", `Bearer ${superAdminToken}`);

    expect(res.status).not.toBe(404);
  });

  it("C. Regular admin is denied (403)", async () => {
    const res = await request(app)
      .get("/admin/admins")
      .set("Authorization", `Bearer ${regularAdminToken}`);

    expect(res.status).toBe(403);
    expect(res.body.success).toBe(false);
  });

  it("D. Unauthenticated request is denied (401)", async () => {
    const res = await request(app).get("/admin/admins");

    expect(res.status).toBe(401);
    expect(res.body.success).toBe(false);
  });
});

// ── POST /register/admin — success path ──────────────────────────────────────

describe("POST /register/admin — success path", () => {
  it("E. Valid invite lets a new admin register (201)", async () => {
    const validInvite = {
      id: 10,
      tokenHash: "sha256-hash-of-valid-token",
      expiresAt: new Date(Date.now() + 86400_000),
      usedAt: null,
      createdById: 1,
      usedById: null,
      createdAt: new Date(),
    };

    (prisma.adminInvite.findUnique as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce(validInvite);

    // findAdminByEmail — no existing admin with that email
    (prisma.admin.findUnique as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce(null);

    const newAdmin = {
      id: 99,
      name: "New Admin",
      email: "new@joemasky.com",
      password: "$2b$10$hashedpassword",
      role: "ADMIN",
      isActive: true,
      createdAt: new Date(),
      updatedAt: new Date(),
    };

    // createAdmin
    (prisma.admin.create as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce(newAdmin);

    // markInviteAsUsed — adminInvite.update
    (prisma.adminInvite.update as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce({ ...validInvite, usedById: 99, usedAt: new Date() });

    const res = await request(app)
      .post("/register/admin")
      .send({
        name: "New Admin",
        email: "new@joemasky.com",
        password: "Secure1@Password",
        inviteToken: "valid-raw-token",
      });

    expect(res.status).toBe(201);
    expect(res.body.success).toBe(true);
    expect(res.body.data.email).toBe("new@joemasky.com");
    expect(res.body.data.role).toBe("ADMIN");
    // Password must never be in the response
    expect(res.body.data).not.toHaveProperty("password");
  });
});



